#!/bin/bash
# Install Favnyr file browser

set -euo pipefail

. "$(dirname "$0")/lib.sh"

log() {
    printf '\n\033[1;34m[install-favnyr] ==> %s\033[0m\n' "$*"
}

warn() {
    printf '\n\033[1;33m[install-favnyr] WARN: %s\033[0m\n' "$*" >&2
}

log "Installing Favnyr file browser"

target="$1"
if [ -z "$target" ] || [ "$target" = "/" ]; then
    target="$WORK_DIR/rootfs"
fi

log "Installing Favnyr to $target"

# Create binary directory
mkdir -p "$target/usr/local/bin"

# Copy Favnyr binary from source
FAVNYR_SOURCE="/home/brunux/Dev/Favnyr-0.3.6/target/release/favnyr"
FAVNYR_BINARY="$target/usr/local/bin/favnyr"

if [ ! -f "$FAVNYR_SOURCE" ]; then
    error "Favnyr binary not found at $FAVNYR_SOURCE"
    exit 1
fi

log "Copying Favnyr binary"
cp "$FAVNYR_SOURCE" "$FAVNYR_BINARY"
chmod 0755 "$FAVNYR_BINARY"

# Create application menu entry
mkdir -p "$target/usr/share/applications"
cat > "$target/usr/share/applications/favnyr.desktop" <<'EOF'
[Desktop Entry]
Name=Favnyr
Comment=A modern file browser with tabbed interface and workspace management
Exec=favnyr
Terminal=false
Type=Application
Categories=Utility;FileManager;FileTools;
Icon=applications-system
StartupWMClass=favnyr
X-MultipleFiles=true
X-GNOME-FullName=Favnyr
X-Purpose=file-management
X-KDE-SubstituteFor=kfmclient
X-KDE-StartupNotify=true
EOF

# Create launcher script for menu integration
mkdir -p "$target/home/$USERNAME/.config/bin"
cat > "$target/home/$USERNAME/.config/bin/favnyr" <<'EOF'
#!/bin/bash
# Favnyr launcher - replaces pcmanfm in LazyOS

export FAIRY_CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}/favnyr"
export FAIRY_DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}/favnyr"

exec favnyr "$@"
EOF
chmod 0755 "$target/home/$USERNAME/.config/bin/favnyr"

# Create Favnyr configuration directory
mkdir -p "$target/home/$USERNAME/.config/favnyr"

# Generate basic Favnyr configuration
cat > "$target/home/$USERNAME/.config/favnyr/config.toml" <<'EOF'
# Favnyr Configuration
# Generated by LazyOS build system for Favnyr 0.3.6

[title]
default_window_title = "Favnyr"

[ui]
# Theme settings
theme = "dark"
font_family = "JetBrains Mono"
font_size = 13

[workspace]
# Workspace settings
max_workspaces = 9
autoname_workspaces = true

[favorites]
# Default favorites (empty by default, users add their own)

[commands]
# Custom commands (empty by default)

[thumbnails]
# Thumbnail settings
max_thumbnail_size = 4096
enable_thumbnails = true

[archive]
# Archive settings
enable_7z = true
enable_zip = true
enable_tar = true

[shortcuts]
# Keyboard shortcuts (uses defaults)
EOF

# Set proper ownership
chown -R "$USERNAME:$USERNAME" "$target/home/$USERNAME/.config/favnyr"
chown -R "$USERNAME:$USERNAME" "$target/home/$USERNAME/.config/bin"
chown -R "$USERNAME:$USERNAME" "$target/usr/share/applications"

log "Favnyr installation complete"
log "  Binary: $FAVNYR_BINARY"
log "  Menu entry: $target/usr/share/applications/favnyr.desktop"
log "  Launcher: $target/home/$USERNAME/.config/bin/favnyr"
log "  Configuration: $target/home/$USERNAME/.config/favnyr/config.toml"

log "Next: Run scripts/install-favnyr.sh / to install on a running system"