//! Templates and the substitution that turns one into a surface.
//!
//! A surface is a file the session already had (a `foot.ini`, a `style.css`, a
//! `mako` config), kept verbatim - comments and all - with its colours replaced
//! by `{{ role }}`. That is Omarchy's model and it is what makes the first
//! `theme set solarized` a no-op: the template *is* the file, and the palette
//! only fills the holes.
//!
//! Three placeholders exist, and nothing else is an expansion:
//!
//! - `{{ role }}` - a semantic role, `#rrggbb`,
//! - `{{ role:bare }}` - the same colour without the `#`, which is the only form
//!   `foot.ini` accepts, and `{{ role:rgb }}` - `0, 43, 54`, which is what
//!   `rgba(...)` needs in a stylesheet that cannot interpolate a hex,
//! - `{{ header }}` - the generated-file header in the comment syntax the
//!   template already uses (the template writes its own `#` or `//`), which is
//!   how `lazyos theme current` can tell what a surface actually contains;
//!   `{{ header:" }}` states the marker instead, for Vimscript,
//! - `{{ home }}` - the user's home, for the one surface that has to name a path
//!   (the wallpaper), and `{{ wallpaper }}` - the theme's first wallpaper.
//!
//! An unknown placeholder is an error naming the template and the key. A
//! template that ships a colour as a literal is also caught: the golden tests
//! render every surface for every built-in theme, and a literal would survive a
//! theme switch that every other line followed.

use crate::theme::Theme;

/// The placeholder syntax, in one place so a template and the renderer cannot
/// disagree about it.
pub const OPEN: &str = "{{";
pub const CLOSE: &str = "}}";

/// The generated-file header. `theme current` reads it back; a surface without
/// one is a file the engine does not own.
pub fn header(theme: &Theme, slug: &str, comment: &str) -> String {
    let claim = format!(
        "LazyOS theme: {} ({slug}) - generated by `lazyos theme set`; do not edit.",
        theme.name
    );
    let change = "Change the theme (`lazyos theme set NAME`) or the template, then set it again.";
    if comment == "/*" {
        // GTK CSS and rasi have no `#` comment: a `#` there is an id selector,
        // and the parser reports "Invalid name of pseudo-class" on line 1
        // (measured: waybar exited on the generated stylesheet).
        format!("/* {claim}\n   {change} */\n")
    } else {
        format!("{comment} {claim}\n{comment} {change}\n")
    }
}

/// Everything a template may ask for besides a colour.
pub struct Context<'a> {
    pub theme: &'a Theme,
    pub slug: &'a str,
    pub home: &'a str,
}

/// Fills a template for a theme. Pure: the same inputs always render the same
/// bytes, which is what makes a second run an empty diff.
pub fn render(template: &str, context: &Context<'_>) -> Result<String, String> {
    let theme = context.theme;
    let slug = context.slug;
    let table = theme.table();
    let mut out = String::with_capacity(template.len() + 256);
    let mut rest = template;
    while let Some(start) = rest.find(OPEN) {
        out.push_str(&rest[..start]);
        let after = &rest[start + OPEN.len()..];
        let Some(end) = after.find(CLOSE) else {
            return Err(format!(
                "an unclosed {OPEN} at byte {} of the template",
                out.len()
            ));
        };
        let key = after[..end].trim();
        let (name, form) = match key.split_once(':') {
            Some((name, form)) => (name.trim(), Some(form.trim())),
            None => (key, None),
        };
        if name == "header"
            && let Some(marker) = form
        {
            // An explicit marker: Vimscript has no `#` comment, so the template
            // says `{{ header:" }}` and the header is written the way that file
            // is commented.
            let text = header(theme, slug, marker);
            out.push_str(text.trim_end_matches('\n'));
        } else if name == "home" {
            out.push_str(context.home);
        } else if name == "wallpaper" {
            // A theme with no wallpaper name keeps the session's own: the
            // template names the file, and an empty one would be a black output.
            out.push_str(
                theme
                    .wallpapers
                    .first()
                    .map(String::as_str)
                    .unwrap_or("lazyos.png"),
            );
        } else if name == "header" {
            // The template chose its own comment marker, so the header does not
            // have to know which file it is in.
            let comment = rest[..start].lines().last().unwrap_or("#").trim_end();
            let comment = if comment.starts_with("/*") {
                "/*"
            } else if comment.starts_with("//") {
                "//"
            } else {
                "#"
            };
            let text = header(theme, slug, comment);
            out.push_str(text.trim_end_matches('\n'));
        } else {
            let colour = table.get(name).ok_or_else(|| {
                let known: Vec<_> = table.keys().copied().collect();
                format!(
                    "unknown role `{name}` in the template (known: {})",
                    known.join(", ")
                )
            })?;
            match form.unwrap_or("hashed") {
                "hashed" => out.push_str(&colour.hashed()),
                "bare" => out.push_str(&colour.bare()),
                "rgb" => out.push_str(&format!("{}, {}, {}", colour.0.r, colour.0.g, colour.0.b)),
                other => {
                    return Err(format!("unknown colour form `{other}` (hashed, bare, rgb)"));
                }
            }
        }
        rest = &after[end + CLOSE.len()..];
    }
    out.push_str(rest);
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn solarized() -> Theme {
        Theme::parse(crate::builtin::SOLARIZED).unwrap()
    }

    fn render(template: &str, theme: &Theme, slug: &str) -> Result<String, String> {
        let theme = theme.clone();
        super::render(
            template,
            &Context {
                theme: &theme,
                slug,
                home: "/home/lazy",
            },
        )
    }

    #[test]
    fn a_role_is_written_hashed_or_bare_and_nothing_else() {
        let theme = solarized();
        assert_eq!(
            render("a={{ accent }} b={{ accent:bare }}", &theme, "solarized").unwrap(),
            "a=#2aa198 b=2aa198"
        );
        assert_eq!(
            render("{{ text }}", &theme, "solarized").unwrap(),
            "#93a1a1"
        );
    }

    #[test]
    fn an_unknown_role_names_itself_and_the_roles_that_exist() {
        let error = render("{{ acccent }}", &solarized(), "solarized").unwrap_err();
        assert!(error.contains("acccent"), "{error}");
        assert!(error.contains("accent"), "{error}");
        let error = render("{{accent:hex}}", &solarized(), "solarized").unwrap_err();
        assert!(error.contains("hex"), "{error}");
    }

    #[test]
    fn a_theme_switch_moves_every_placeholder() {
        let template = "bg={{ surface }} fg={{ text }} accent={{ accent }}";
        let solarized = render(template, &solarized(), "solarized").unwrap();
        let mocha_text = crate::builtin::CATPPUCCIN;
        let mocha = render(template, &Theme::parse(mocha_text).unwrap(), "catppuccin").unwrap();
        assert_ne!(solarized, mocha, "a theme switch has to change the output");
        assert!(!mocha.contains("2aa198"), "no solarized value may survive");
    }

    #[test]
    fn the_header_names_the_theme_and_the_slug() {
        let text = render("# a file\n{{ header }}\n", &solarized(), "solarized").unwrap();
        assert!(text.contains("Solarized Dark (solarized)"), "{text}");
        assert!(
            text.contains("# LazyOS theme:"),
            "the template's comment style wins: {text}"
        );
        let text = render("// js\n{{ header }}\n", &solarized(), "solarized").unwrap();
        assert!(text.contains("// LazyOS theme:"), "{text}");
    }

    #[test]
    fn an_unclosed_placeholder_is_an_error_not_the_end_of_the_file() {
        assert!(render("a {{ accent", &solarized(), "solarized").is_err());
    }
}
